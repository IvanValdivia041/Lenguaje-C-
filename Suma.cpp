#include <iostream>
using namespace std;

int main () {
	//Realiza un programa que permita la suma de dos numeros
	//Definir variables
	int numero1;
	int numero2; 
	int suma;  
	//Entrada 
	cout << "Ingrese el primer numero: ";
	cin >> numero1;
	cout << "Ingrese el segundo numero: ";
	cin >> numero2;
	//Proceso 
	suma=numero1+numero2;
	//Salida
	cout << "El resultado de la suma es: " << suma;

	
	return 0;
}
